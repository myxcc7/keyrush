/** 数字模式位数：简单 15 位 / 中等 50 位 / 困难 100 位 */
export const DIGIT_LENGTHS = { easy: 15, medium: 50, hard: 100 };

/** 生成随机数字串，每 4 位用空格分组，防止看花眼 */
export function generateDigits(difficulty) {
  const total = DIGIT_LENGTHS[difficulty] || DIGIT_LENGTHS.easy;
  const groups = [];
  let remaining = total;
  while (remaining > 0) {
    const size = Math.min(4, remaining);
    let group = '';
    for (let i = 0; i < size; i += 1) group += String(Math.floor(Math.random() * 10));
    groups.push(group);
    remaining -= size;
  }
  return groups.join(' ');
}

export function pickText(difficulty, exclude, lang) {
  if (lang === 'digit') return generateDigits(difficulty);
  const source = lang === 'en' ? TEXTS_EN : TEXTS;
  const pool = source[difficulty] || source.easy;
  const candidates = pool.filter((text) => text !== exclude);
  const list = candidates.length ? candidates : pool;
  return list[Math.floor(Math.random() * list.length)];
}

export function textIdOf(text) {
  let hash = 0;
  for (let i = 0; i < text.length; i += 1) {
    hash = (hash * 31 + text.charCodeAt(i)) >>> 0;
  }
  return hash.toString(36);
}
